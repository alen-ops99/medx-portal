          function persistServer(loc){
            if(!hasToken()) return;
            var tk; try{ tk=(window.UserPortal&&UserPortal.token)||localStorage.getItem('medx_user_token'); }catch(e){ return; }
            try{
              fetch(apiBase()+'/api/me',{
                method:'PATCH',
                headers:{'Content-Type':'application/json','Authorization':'Bearer '+tk},
                body:JSON.stringify({locale:loc})
              }).catch(function(){});
            }catch(e){}
          }

          // Set the active locale and apply everywhere, live, with no reload.
          function set(loc, opts){
            opts=opts||{};
            if(!isSupported(loc)) loc='en';
            _locale=loc;
            try{ document.documentElement.setAttribute('lang', loc); }catch(e){}
            if(!opts.silentStore){ safeLS(function(){ localStorage.setItem(LS_KEY, loc); localStorage.setItem(LS_SET,'1'); }); }
            apply(document);
            updateToggles();
            startObserverIfNeeded();
            if(!opts.noServer) persistServer(loc);
            try{ document.dispatchEvent(new CustomEvent('medx:localechange',{detail:{locale:loc}})); }catch(e){}
          }

          function dateLocale(){ return _locale==='hr' ? 'hr-HR' : 'en-US'; }
          function formatDate(dateish, o){
            try{
              var d=(dateish instanceof Date)?dateish:new Date(dateish);
              if(isNaN(d.getTime())) return String(dateish==null?'':dateish);
              return d.toLocaleDateString(dateLocale(), o||{day:'numeric',month:'long',year:'numeric'});
            }catch(e){ return String(dateish==null?'':dateish); }
          }

          // Lightweight observer: only runs while a non-English locale is active, so an
          // English session pays nothing. Re-localizes dynamically injected data-i18n nodes.
          var _obs=null, _obsTimer=null;
          function startObserverIfNeeded(){
            if(_locale==='en'){ if(_obs){ _obs.disconnect(); _obs=null; } return; }
            if(_obs) return;
            if(typeof MutationObserver==='undefined') return;
            var app=document.body; if(!app) return;
            _obs=new MutationObserver(function(muts){
              for(var i=0;i<muts.length;i++){ if(muts[i].addedNodes && muts[i].addedNodes.length){
                clearTimeout(_obsTimer);
                _obsTimer=setTimeout(function(){ apply(document); }, 140);
                return;
              } }
            });
            try{ _obs.observe(app,{childList:true,subtree:true}); }catch(e){ _obs=null; }
          }

          // Adopt the profile's saved locale on a device that has no local choice yet;
          // otherwise reconcile the server to the local choice.
          function hydrateFromServer(){
            if(!hasToken()) return;
            var tk; try{ tk=(window.UserPortal&&UserPortal.token)||localStorage.getItem('medx_user_token'); }catch(e){ return; }
            try{
              fetch(apiBase()+'/api/me/locale',{headers:{'Authorization':'Bearer '+tk}})
                .then(function(r){ return r&&r.ok?r.json():null; })
                .then(function(d){
                  if(!d) return;
                  var explicit=safeLS(function(){ return localStorage.getItem(LS_SET); });
                  if(!explicit && d.locale && isSupported(d.locale)){
                    if(d.locale!==_locale) set(d.locale,{noServer:true});
                  } else if(explicit && d.locale!==_locale){
                    persistServer(_locale);
                  }
                }).catch(function(){});
            }catch(e){}
          }

          function boot(){
            var saved=safeLS(function(){ return localStorage.getItem(LS_KEY); });
            _locale=isSupported(saved)?saved:'en';
            try{ document.documentElement.setAttribute('lang', _locale); }catch(e){}
            var run=function(){ apply(document); updateToggles(); startObserverIfNeeded(); };
            if(document.readyState!=='loading') run();
            else document.addEventListener('DOMContentLoaded', run);
            // Late reconcile with the member profile once a session is known.
            window.addEventListener('load', function(){ setTimeout(hydrateFromServer, 400); });
          }

