          // t('key' [, vars]) — JS-generated strings. Interpolates {name} tokens.
          function t(key, vars){
            var s=lookup(key,_locale);
            if(s==null) s=key; // key not registered yet — surface the key (dev signal)
            if(vars){ s=s.replace(/\{(\w+)\}/g,function(m,k){ return (vars[k]!=null)?String(vars[k]):m; }); }
            return s;
          }

          // Replace the FIRST significant direct text node, preserving surrounding
          // whitespace and any child elements (icons / badges). No span-wrapping needed.
          function setText(el, str){
            var kids=el.childNodes, i, n;
            for(i=0;i<kids.length;i++){
              n=kids[i];
              if(n.nodeType===3 && n.nodeValue && n.nodeValue.trim()!==''){
                var m=n.nodeValue.match(/^(\s*)[\s\S]*?(\s*)$/);
                n.nodeValue=(m?m[1]:'')+str+(m?m[2]:'');
                return;
              }
            }
            el.insertBefore(document.createTextNode(str), el.firstChild);
          }

          // DOM pass: localize every registered data-i18n* element under root.
          function apply(root){
            root=root||document;
            var sel='[data-i18n],[data-i18n-html],[data-i18n-placeholder],[data-i18n-aria-label],[data-i18n-title]';
            var els; try{ els=root.querySelectorAll(sel); }catch(e){ return; }
            for(var i=0;i<els.length;i++){
              var el=els[i], k;
              if((k=el.getAttribute('data-i18n')) && DICT[k]) setText(el, lookup(k,_locale));
              if((k=el.getAttribute('data-i18n-html')) && DICT[k]) el.innerHTML=lookup(k,_locale);
              if((k=el.getAttribute('data-i18n-placeholder')) && DICT[k]) el.setAttribute('placeholder', lookup(k,_locale));
              if((k=el.getAttribute('data-i18n-aria-label')) && DICT[k]) el.setAttribute('aria-label', lookup(k,_locale));
              if((k=el.getAttribute('data-i18n-title')) && DICT[k]) el.setAttribute('title', lookup(k,_locale));
            }
          }

